import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { startHarness } from './browser-harness.mjs'

const harness = await startHarness()
const output = new URL('../docs/verify/ui-refresh/', import.meta.url)
await mkdir(output, { recursive: true })
let browser
try {
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || (process.env.CI ? 'chrome' : 'msedge'), headless: true, args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(harness.url)
  await page.waitForSelector('iframe[title="ShaderToy 背景设置"]')
  const frame = page.frames().find(frame => frame.url().includes('panel.html'))
  await frame.waitForSelector('.settings-card')
  const shot = name => page.screenshot({ path: new URL(name + '.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') })
  const noOverflow = async () => assert.ok(await frame.evaluate(() => document.body.scrollWidth <= innerWidth), 'page must not overflow horizontally')
  assert.equal(await frame.locator('.settings-card').count(), 4)
  assert.equal(await frame.getAttribute('#tab-params', 'aria-selected'), 'true')
  assert.ok(await frame.locator('#audio-mode-dd .dd-trigger').isDisabled())
  assert.equal(await frame.evaluate(() => getComputedStyle(document.querySelector('.settings-grid')).gridTemplateColumns.split(' ').length), 2)
  await shot('settings-dark')
  await frame.click('.wallpaper-preview')
  assert.equal(await frame.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgba(0, 0, 0, 0)')
  await page.screenshot({ path: new URL('background-preview.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') })
  await frame.press('.wallpaper-preview', 'Escape')
  assert.equal(await frame.getAttribute('.wallpaper-preview', 'aria-pressed'), 'false')
  console.log('ok    grouped settings, silent controls and background preview / Escape')

  await page.evaluate(() => document.body.removeAttribute('data-ds-dark-theme'))
  await frame.waitForFunction(() => document.documentElement.dataset.theme === 'light')
  await shot('settings-light')
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await frame.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
  await frame.focus('#tab-params')
  await page.keyboard.press('ArrowRight')
  assert.equal(await frame.getAttribute('#tab-library', 'aria-selected'), 'true')
  assert.ok(await frame.locator('#note').isVisible(), 'status remains visible on the library tab')
  await shot('library-dark')
  console.log('ok    parent theme changes and keyboard tab navigation')

  await frame.click('#tab-params')
  await frame.click('#preset-dd .dd-trigger')
  await frame.press('#preset-dd .dd-trigger', 'End')
  await frame.press('#preset-dd .dd-trigger', 'Enter')
  await frame.waitForFunction(() => document.querySelector('#preset-dd .dd-trigger').textContent.includes('马里奥'))
  await frame.waitForFunction(() => !document.querySelector('#audio-mode-dd .dd-trigger').disabled)
  await frame.click('#audio-mode-dd .dd-trigger')
  await frame.locator('#audio-mode-dd .dd-item').filter({ hasText: '只播一次' }).click()
  assert.equal(await frame.textContent('#audio-mode-out'), '只播一次')
  console.log('ok    dropdown keyboard selection and sound controls on audible works')

  await frame.click('#tab-code')
  await frame.waitForFunction(() => document.querySelector('#code-image').value.includes('mainImage'))
  await noOverflow()
  await shot('editor-dark')
  const area = frame.locator('#code-image')
  const grip = frame.locator('.code-grip').first()
  await grip.focus()
  await page.keyboard.press('End')
  assert.equal(await area.evaluate(node => node.offsetHeight), 1200, 'height can exceed the old viewport cap')
  await grip.dblclick()
  assert.equal(await area.evaluate(node => node.offsetHeight), 360)
  await area.evaluate(node => { node.scrollTop = 240; node.dispatchEvent(new Event('scroll')) })
  assert.equal(await frame.locator('#code-image-lines').evaluate(node => node.scrollTop), await area.evaluate(node => node.scrollTop))
  const oldScroll = await area.evaluate(node => node.scrollTop)
  await frame.click('[data-focus="code-image"]')
  assert.equal(await area.evaluate(node => node.scrollTop), oldScroll)
  assert.ok(await frame.locator('.focused .editor-focus-save').isVisible())
  const bounds = await frame.locator('.focused').boundingBox()
  assert.ok(bounds.height >= 950)
  await shot('editor-focus')
  await page.keyboard.press('Escape')
  assert.equal(await frame.locator('.code-card.focused').count(), 0)
  assert.equal(await area.evaluate(node => node.offsetHeight), 360)
  await frame.locator('.code-card').nth(1).getByRole('button', { name: '收起', exact: true }).click()
  assert.ok(!await frame.locator('#code-sound-frame').isVisible())
  await frame.check('#code-wrap')
  await frame.selectOption('#code-font', '18')
  assert.equal(await area.evaluate(node => getComputedStyle(node).fontSize), '18px')
  assert.ok(!await frame.locator('#code-image-lines').isVisible(), 'wrapped lines do not show misleading line numbers')
  console.log('ok    tall resize, reset, line gutter, focus position, collapse, wrap and font size')

  await page.reload()
  await page.waitForSelector('iframe[title="ShaderToy 背景设置"]')
  const restored = page.frames().find(frame => frame.url().includes('panel.html'))
  await restored.waitForSelector('#preset-dd .dd-trigger')
  await restored.click('#tab-code')
  await restored.waitForFunction(() => document.querySelector('#code-image').value.includes('mainImage'))
  assert.equal(await restored.locator('#code-image').evaluate(node => node.offsetHeight), 360)
  assert.equal(await restored.locator('#code-image').evaluate(node => getComputedStyle(node).fontSize), '18px')
  assert.ok(await restored.locator('#code-wrap').isChecked())
  console.log('ok    editor height and reading preferences survive reload')

  await page.setViewportSize({ width: 390, height: 844 })
  await restored.click('#tab-params')
  assert.ok(await restored.evaluate(() => document.body.scrollWidth <= innerWidth))
  assert.equal(await restored.evaluate(() => getComputedStyle(document.querySelector('.settings-grid')).gridTemplateColumns.split(' ').length), 1)
  await shot('settings-narrow')
  await restored.click('#tab-library')
  assert.ok(await restored.evaluate(() => document.body.scrollWidth <= innerWidth))
  await shot('library-narrow')
  await restored.click('#tab-code')
  await restored.waitForFunction(() => document.querySelector('#code-image').value.includes('mainImage'))
  assert.ok(await restored.evaluate(() => document.body.scrollWidth <= innerWidth))
  await shot('editor-narrow')
  assert.deepEqual(errors, [])
  console.log('ok    390px settings / library / editor layouts and no uncaught errors')
  console.log('UI regressions ok; screenshots in docs/verify/ui-refresh/')
} finally {
  await browser?.close()
  await harness.close()
}
